SELECT
    Month,
    COUNT(*) AS Record_Count,
    SUM(Arrivals) AS Monthly_Arrivals
FROM dbo.Tourism_2020_Cleaned1
GROUP BY Month
ORDER BY MIN(
    CASE Month
        WHEN 'January' THEN 1
        WHEN 'February' THEN 2
        WHEN 'March' THEN 3
        WHEN 'April' THEN 4
        WHEN 'May' THEN 5
        WHEN 'June' THEN 6
        WHEN 'July' THEN 7
        WHEN 'August' THEN 8
        WHEN 'September' THEN 9
        WHEN 'October' THEN 10
        WHEN 'November' THEN 11
        WHEN 'December' THEN 12
        ELSE 13
    END
);